#!/usr/bin/env node
/* Evaluation runner.
 *
 *   node eval/run.js                          # all cases, offline responder, rule grader (free)
 *   node eval/run.js --phase pilot            # only pilot cases
 *   node eval/run.js --responder dump-answer  # negative control (should fail badly)
 *   node eval/run.js --controls               # run every negative control and report pass rates
 *   node eval/run.js --model-estimate         # dry run: tokens + cost for the optional model judge
 *   node eval/run.js --model-judge --live --budget-usd 2 --confirm-billing   # paid; see README first
 *
 * Writes eval/results/<name>.json and .md unless --no-write.
 */
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const content = require("../js/content.js");
const { validateCase, CATEGORIES } = require("./lib/schema.js");
const { respond } = require("./lib/responder-offline.js");
const { CONTROLS } = require("./lib/responders-control.js");
const { grade, DIMENSIONS } = require("./lib/grade-rules.js");

function args(argv) {
  const a = { phase: null, responder: "offline", write: true, controls: false, modelEstimate: false, modelJudge: false, live: false, budgetUsd: null, confirmBilling: false, model: "claude-opus-5-5", maxCases: null, concurrency: 2, batchSize: 10, effort: "medium" };
  for (let i = 2; i < argv.length; i++) {
    const k = argv[i];
    const v = () => argv[++i];
    if (k === "--phase") a.phase = v();
    else if (k === "--responder") a.responder = v();
    else if (k === "--no-write") a.write = false;
    else if (k === "--controls") a.controls = true;
    else if (k === "--model-estimate") a.modelEstimate = true;
    else if (k === "--model-judge") a.modelJudge = true;
    else if (k === "--live") a.live = true;
    else if (k === "--budget-usd") a.budgetUsd = Number(v());
    else if (k === "--confirm-billing") a.confirmBilling = true;
    else if (k === "--model") a.model = v();
    else if (k === "--max-cases") a.maxCases = Number(v());
    else if (k === "--concurrency") a.concurrency = Math.max(1, Math.min(4, Number(v())));
    else if (k === "--batch-size") a.batchSize = Math.max(1, Math.min(50, Number(v())));
    else if (k === "--effort") a.effort = v();
    else throw new Error(`Unknown option ${k}`);
  }
  return a;
}

function loadCases(phase) {
  const dir = path.join(__dirname, "cases");
  const all = fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort().flatMap((f) => JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")));
  // Cases name the right common problem by its English symptom text, so editing the course
  // (adding or reordering problems) cannot silently point a case at the wrong one.
  const missing = [];
  all.forEach((c) => {
    const ref = c.expected && c.expected.problemRef;
    if (!ref) { if (c.expected && c.expected.problem === undefined) c.expected.problem = null; return; }
    const lesson = content.lessons.find((l) => l.id === c.lesson);
    const i = lesson ? lesson.problems.findIndex((p) => p.symptom.en === ref) : -1;
    if (i < 0) missing.push(`${c.id}: problemRef not found in L${c.lesson}: ${ref}`);
    c.expected.problem = i < 0 ? null : i;
  });
  if (missing.length) throw new Error("Stale problem references:\n" + missing.join("\n"));
  const errs = all.flatMap((c) => validateCase(c, content));
  const ids = all.map((c) => c.id);
  ids.forEach((id, i) => { if (ids.indexOf(id) !== i) errs.push(`duplicate id ${id}`); });
  if (errs.length) throw new Error("Invalid cases:\n" + errs.join("\n"));
  return phase ? all.filter((c) => c.phase === phase) : all;
}

function responderFor(name) {
  if (name === "offline") return (c) => respond(c, content);
  if (CONTROLS[name]) return (c) => CONTROLS[name](c, content);
  throw new Error(`Unknown responder ${name}. Use offline or one of: ${Object.keys(CONTROLS).join(", ")}`);
}

function evaluate(cases, responderName) {
  const r = responderFor(responderName);
  return cases.map((c) => { const out = r(c); return { id: c.id, category: c.category, lesson: c.lesson, input: c.input, response: out, grade: grade(c, out, content) }; });
}

function summarize(rows) {
  const n = rows.length;
  const pass = rows.filter((x) => x.grade.pass).length;
  const dims = Object.fromEntries(DIMENSIONS.map((d) => [d, rows.reduce((s, x) => s + x.grade.scores[d], 0) / (2 * n)]));
  const byCategory = {};
  rows.forEach((x) => { const b = (byCategory[x.category] = byCategory[x.category] || { n: 0, pass: 0 }); b.n++; if (x.grade.pass) b.pass++; });
  const failures = {};
  rows.forEach((x) => x.grade.failures.forEach((f) => { failures[f] = (failures[f] || 0) + 1; }));
  return { n, pass, passRate: n ? pass / n : 0, dims, byCategory, failures };
}

function markdown(title, s, rows) {
  const pct = (x) => (100 * x).toFixed(0) + "%";
  let md = `# ${title}\n\n`;
  md += `Generated by \`node eval/run.js\` (rule grader, deterministic). These are screening scores for fictional cases; they do not show that any Scratch project runs.\n\n`;
  md += `| Cases | Passed | Pass rate |\n|---|---|---|\n| ${s.n} | ${s.pass} | ${pct(s.passRate)} |\n\n`;
  md += `## Dimensions (average score as % of max)\n\n| Dimension | Score |\n|---|---|\n` + DIMENSIONS.map((d) => `| ${d} | ${pct(s.dims[d])} |`).join("\n") + "\n\n";
  md += `## By category\n\n| Category | 中文 | Cases | Passed |\n|---|---|---|---|\n` + Object.entries(s.byCategory).map(([k, v]) => `| ${k} | ${CATEGORIES[k]} | ${v.n} | ${v.pass} |`).join("\n") + "\n\n";
  md += `## Triggered failure conditions\n\n` + (Object.keys(s.failures).length ? "| Failure | Cases |\n|---|---|\n" + Object.entries(s.failures).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| ${k} | ${v} |`).join("\n") : "None.") + "\n\n";
  const failed = rows.filter((x) => !x.grade.pass);
  md += `## Failed cases\n\n` + (failed.length ? failed.map((x) => `- **${x.id}** (${x.category}, L${x.lesson}): ${x.grade.failures.join(", ") || "low dimension score"} ${x.grade.notes.length ? "— " + x.grade.notes.join("; ") : ""} · scores ${JSON.stringify(x.grade.scores)}`).join("\n") : "None.") + "\n";
  return md;
}

async function main() {
  const a = args(process.argv);
  let cases = loadCases(a.phase);
  if (a.maxCases) cases = cases.slice(0, a.maxCases);
  const tag = a.phase || "all";
  const outDir = path.join(__dirname, "results");

  if (a.controls) {
    const table = Object.keys(CONTROLS).map((name) => ({ name, ...summarize(evaluate(cases, name)) }));
    table.forEach((t) => console.log(`${t.name.padEnd(14)} pass ${t.pass}/${t.n}  dims ${DIMENSIONS.map((d) => d + "=" + (100 * t.dims[d]).toFixed(0)).join(" ")}`));
    if (a.write) {
      fs.mkdirSync(outDir, { recursive: true });
      const md = `# Negative controls (${tag})\n\nDeliberately bad responders. A sound grader must fail them.\n\n| Responder | Passed | ` + DIMENSIONS.join(" | ") + " |\n|---|---|" + DIMENSIONS.map(() => "---").join("|") + "|\n" +
        table.map((t) => `| ${t.name} | ${t.pass}/${t.n} | ` + DIMENSIONS.map((d) => (100 * t.dims[d]).toFixed(0) + "%").join(" | ") + " |").join("\n") + "\n";
      fs.writeFileSync(path.join(outDir, `controls-${tag}.md`), md);
    }
    return table;
  }

  const rows = evaluate(cases, a.responder);
  const s = summarize(rows);
  console.log(`${a.responder}: ${s.pass}/${s.n} passed (${(100 * s.passRate).toFixed(0)}%)`);
  DIMENSIONS.forEach((d) => console.log(`  ${d.padEnd(14)} ${(100 * s.dims[d]).toFixed(0)}%`));
  if (Object.keys(s.failures).length) console.log("  failures:", JSON.stringify(s.failures));
  if (a.write) {
    fs.mkdirSync(outDir, { recursive: true });
    const name = `${a.responder}-${tag}`;
    fs.writeFileSync(path.join(outDir, `${name}.json`), JSON.stringify({ summary: s, rows }, null, 2) + "\n");
    fs.writeFileSync(path.join(outDir, `${name}.md`), markdown(`Eval: ${a.responder} responder, ${tag} cases`, s, rows));
  }

  if (a.modelEstimate || a.modelJudge) {
    const { estimate, runLive } = require("./lib/grade-model.js");
    const pairs = rows.map((x) => ({ c: cases.find((c) => c.id === x.id), r: x.response }));
    const est = estimate(pairs, content, a.model);
    console.log(`\nModel judge estimate (${est.model}, ${est.calls} calls): input ≈ ${est.inputTokens} tokens, output ≈ ${est.outputTokensLow}–${est.outputTokensHigh} tokens, cost ≈ $${est.usdLow.toFixed(2)}–$${est.usdHigh.toFixed(2)}`);
    console.log(est.note);
    if (a.modelJudge) {
      if (!a.live) { console.log("Dry run only (add --live to call the API). No request was sent."); return; }
      if (!a.budgetUsd || !(a.budgetUsd > 0)) throw new Error("--budget-usd is required for a live run.");
      if (!a.confirmBilling) throw new Error("--confirm-billing is required: confirm which organization/credit pool your API key bills to. This tool cannot verify it.");
      fs.mkdirSync(outDir, { recursive: true });
      const logFile = path.join(outDir, `model-judge-${tag}-${Date.now()}.jsonl`);
      const res = await runLive(pairs, content, { model: a.model, budgetUsd: a.budgetUsd, concurrency: a.concurrency, batchSize: a.batchSize, effort: a.effort, logFile });
      console.log(`Model judge finished: ${res.results.length} results, spent ≈ $${res.spent.toFixed(3)}${res.stoppedForBudget ? " (stopped at 80% of budget)" : ""}. Log: ${path.relative(process.cwd(), logFile)}`);
      fs.writeFileSync(logFile.replace(/\.jsonl$/, "-results.json"), JSON.stringify(res, null, 2));
    }
  }
  return s;
}

if (require.main === module) main().catch((e) => { console.error(e.message); process.exit(1); });
module.exports = { loadCases, evaluate, summarize, main };
